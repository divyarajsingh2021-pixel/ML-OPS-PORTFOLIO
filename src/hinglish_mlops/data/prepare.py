"""Assemble clean, leak-checked train/val/test splits and the OOD eval set.

Run after ``download.py``::

    python -m hinglish_mlops.data.prepare

Pipeline:

1. Parse the official SentiMix train/dev/test splits (labels for test come from
   the separate labels file).
2. Clean every example with :func:`hinglish_mlops.data.clean.clean_text`, drop
   examples that become empty and exact duplicates.
3. Enforce split hygiene: no cleaned text may appear in more than one of
   train/val/test (a leakage guard).
4. Load the YouTube Hinglish dataset, clean it, and drop any row whose text
   overlaps the SentiMix data (it is evaluation-only).

Outputs (git-ignored): ``data/processed/sentimix_{train,val,test}.csv`` and
``data/processed/shae_eval.csv`` (columns ``uid, text, text_clean, label``).
Artifacts (committed): ``reports/data_stats.json`` and ``reports/data_card.md``.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd

from ..config import LABELS, MANIFEST_PATH, PROCESSED_DIR, RAW_DIR, REPORTS_DIR
from . import sentimix, shae
from .clean import clean_series
from .download import load_manifest
from .sources import SOURCES

SPLIT_FILES = {
    "train": "sentimix_train.csv",
    "val": "sentimix_val.csv",
    "test": "sentimix_test.csv",
}
EVAL_FILE = "shae_eval.csv"
STATS_FILE = "data_stats.json"
DATA_CARD_FILE = "data_card.md"

COLUMNS = ["uid", "text", "text_clean", "label"]


def _validate_labels(frame: pd.DataFrame, name: str) -> None:
    missing = int(frame["label"].isna().sum())
    if missing:
        raise ValueError(f"{name}: {missing} rows are missing a label")
    unknown = sorted(set(frame["label"].unique()) - set(LABELS))
    if unknown:
        raise ValueError(f"{name}: unexpected labels {unknown}")


def _clean_and_filter(frame: pd.DataFrame, name: str) -> tuple[pd.DataFrame, dict[str, int]]:
    frame = frame.copy()
    frame["text"] = frame["text"].fillna("").astype(str)
    frame["text_clean"] = clean_series(frame["text"])
    _validate_labels(frame, name)
    n_before = len(frame)
    frame = frame[frame["text_clean"].str.len() > 0]
    empty_removed = n_before - len(frame)
    before_dedup = len(frame)
    frame = frame.drop_duplicates(subset="text_clean", keep="first")
    duplicate_removed = before_dedup - len(frame)
    frame = frame.reset_index(drop=True)
    return frame, {"empty_removed": empty_removed, "duplicate_removed": duplicate_removed}


def _split_stats(frame: pd.DataFrame) -> dict[str, object]:
    tokens = frame["text_clean"].str.split().map(len)
    counts = frame["label"].value_counts().reindex(LABELS, fill_value=0)
    return {
        "n": int(len(frame)),
        "class_counts": {label: int(counts[label]) for label in LABELS},
        "mean_tokens": round(float(tokens.mean()), 2) if len(frame) else 0.0,
        "median_tokens": float(tokens.median()) if len(frame) else 0.0,
        "max_tokens": int(tokens.max()) if len(frame) else 0,
    }


def _write_csv(frame: pd.DataFrame, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    frame[COLUMNS].to_csv(path, index=False, encoding="utf-8")


def _render_data_card(stats: dict[str, object]) -> str:
    splits = stats["splits"]
    rows = []
    for name, info in splits.items():
        counts = info["class_counts"]
        total = info["n"] or 1
        distribution = " / ".join(
            f"{counts[label]} ({counts[label] / total:.0%})" for label in LABELS
        )
        rows.append(
            f"| {name} | {info['n']:,} | {distribution} | "
            f"{info['mean_tokens']:.1f} | {info['max_tokens']:,} |"
        )
    table = "\n".join(rows)

    source_lines = "\n".join(
        f"- `{rel}` <- {url}  (sha256 `{sha[:12]}...`)" for rel, url, sha in stats["sources"]
    )

    return f"""# Data card -- hinglish-mlops

_Generated by `python -m hinglish_mlops.data.prepare`. Do not edit by hand._

## Overview

Three-class (negative / neutral / positive) sentiment classification of Hinglish
(Hindi-English, Roman-script) social media text. Training, validation and test
come from SemEval-2020 Task 9 (SentiMix); an independent YouTube dataset is held
out for cross-dataset (out-of-distribution) evaluation only.

## Sources

{source_lines}

See `data/manifest.sha256` for full checksums. Raw files are git-ignored and
re-fetched with `inv download-data`.

| Dataset | Licence | Role |
|---------|---------|------|
| SentiMix (SemEval-2020 Task 9, Hinglish) | CC-BY-4.0 | train / val / test |
| shae2977 YouTube Hinglish comments | CC-BY-4.0 | OOD eval only (never trained on) |

## Splits

Official SentiMix splits are used unchanged: train 14k / dev 3k / test 3k
(approximately 70 / 15 / 15).

| Split | Examples | Class distribution (neg / neu / pos) | Mean tokens | Max tokens |
|-------|---------:|--------------------------------------|------------:|-----------:|
{table}

## Cleaning

Lower-cased; HTML entities unescaped; URLs, @mentions and the `#` of hashtags
removed (hashtag words kept); whitespace collapsed. Cleaning is applied to the
concatenated tokens as released, so it also strips the whitespace-split URL and
mention artefacts of the CoNLL reconstruction.

## Leakage guard

No cleaned text shared between train/val/test. Rows in the eval set overlapping
SentiMix are dropped. Filter counts:

```json
{json.dumps(stats["filters"], indent=2)}
```

## Intended use

Baseline and improved classical models (TF-IDF + linear models) for code-mixed
Hinglish sentiment, plus an end-to-end MLOps demonstration. English or
Devanagari-only text is out of scope.

## Known limitations

- Romanised Hinglish is noisy: spelling varies, and Hindi is written
  inconsistently (e.g. `hai`/`h`/`ha`).
- The SentiMix text is reconstructed by joining tokens with spaces, so
  punctuation spacing is approximate; a small number of
  whitespace-broken URLs (e.g. split by an ellipsis) survive cleaning.
- The eval set is a different domain (YouTube comments) and is class-imbalanced
  (negative-heavy), so its metrics are not directly comparable to test metrics.
- Labels are crowd-/author-annotated; some examples are inherently ambiguous.

## Citation

```
@inproceedings{{patwa2020semeval,
  title={{SemEval-2020 Task 9: Sentiment Analysis for Code-Mixed Social Media Text}},
  author={{Patwa, Parth and Aguilar, Gustavo and Kar, Sudipta and others}},
  booktitle={{Proceedings of the 14th International Workshop on Semantic Evaluation}},
  pages={{624--655}},
  year={{2020}}
}}
```
"""


def prepare(
    raw_dir: Path = RAW_DIR,
    processed_dir: Path = PROCESSED_DIR,
    reports_dir: Path = REPORTS_DIR,
) -> dict[str, object]:
    """Run the full data-preparation pipeline and write all artifacts."""
    raw_frames = sentimix.load_all(raw_dir)
    filters: dict[str, dict[str, int]] = {}
    cleaned: dict[str, pd.DataFrame] = {}

    for name, frame in raw_frames.items():
        frame, counts = _clean_and_filter(frame, name)
        cleaned[name] = frame
        filters[name] = {**counts, "cross_split_removed": 0}

    # Leakage guard: earlier splits win, later splits drop shared texts.
    seen: set[str] = set()
    for name in ("train", "val", "test"):
        frame = cleaned[name]
        overlap = frame["text_clean"].isin(seen)
        filters[name]["cross_split_removed"] = int(overlap.sum())
        frame = frame[~overlap].reset_index(drop=True)
        cleaned[name] = frame
        seen.update(frame["text_clean"])

    eval_frame, eval_counts = _clean_and_filter(shae.load_shae(raw_dir), "shae_eval")
    eval_overlap = eval_frame["text_clean"].isin(seen)
    filters["shae_eval"] = {**eval_counts, "overlap_with_sentimix_removed": int(eval_overlap.sum())}
    eval_frame = eval_frame[~eval_overlap].reset_index(drop=True)

    for name, filename in SPLIT_FILES.items():
        _write_csv(cleaned[name], processed_dir / filename)
    _write_csv(eval_frame, processed_dir / EVAL_FILE)

    splits_stats = {name: _split_stats(cleaned[name]) for name in ("train", "val", "test")}
    splits_stats["shae_eval"] = _split_stats(eval_frame)

    manifest = load_manifest(MANIFEST_PATH)
    stats: dict[str, object] = {
        "splits": splits_stats,
        "filters": filters,
        "sources": [[rel, SOURCES[rel], manifest[rel]] for rel in SOURCES],
    }

    reports_dir.mkdir(parents=True, exist_ok=True)
    (reports_dir / STATS_FILE).write_text(
        json.dumps(stats, indent=2) + "\n", encoding="utf-8", newline="\n"
    )
    (reports_dir / DATA_CARD_FILE).write_text(
        _render_data_card(stats), encoding="utf-8", newline="\n"
    )
    return stats


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Clean + split datasets and write artifacts.")
    parser.add_argument("--raw-dir", type=Path, default=RAW_DIR)
    parser.add_argument("--processed-dir", type=Path, default=PROCESSED_DIR)
    parser.add_argument("--reports-dir", type=Path, default=REPORTS_DIR)
    args = parser.parse_args(argv)
    stats = prepare(args.raw_dir, args.processed_dir, args.reports_dir)
    for name, info in stats["splits"].items():
        counts = info["class_counts"]
        print(
            f"{name:>10}: {info['n']:>5} rows  "
            f"(neg {counts['negative']}, neu {counts['neutral']}, pos {counts['positive']})"
        )
    print(f"Wrote splits to {args.processed_dir}")
    print(f"Wrote {STATS_FILE} and {DATA_CARD_FILE} to {args.reports_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
