"""Render a comparison of trained models from their metrics reports.

CLI::

    python -m hinglish_mlops.compare

Reads ``reports/<model>_metrics.json`` for every registered model and writes a
markdown summary to ``reports/model_comparison.md``. No models are retrained, so
this is cheap and deterministic; the validation split is the selection split.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from .config import REPORTS_DIR
from .dataset import EVAL_NAME, SPLIT_NAMES
from .modeling import MODEL_BUILDERS
from .train import metrics_artifact_name

COMPARISON_FILE = "model_comparison.md"
SPLIT_ORDER: tuple[str, ...] = (*SPLIT_NAMES, EVAL_NAME)


def load_metrics(model_name: str, reports_dir: Path = REPORTS_DIR) -> dict[str, object] | None:
    """Load the metrics report for ``model_name`` if it exists."""
    path = reports_dir / metrics_artifact_name(model_name)
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def _table(metric: str, reports: dict[str, dict[str, object]]) -> str:
    header = "| Model | " + " | ".join(SPLIT_ORDER) + " |"
    divider = "|" + "---|" * (len(SPLIT_ORDER) + 1)
    rows = [header, divider]
    for name, payload in reports.items():
        metrics = payload["metrics"]
        cells = [
            f"{metrics[split][metric]:.3f}" if split in metrics else "-" for split in SPLIT_ORDER
        ]
        rows.append(f"| {name} | " + " | ".join(cells) + " |")
    return "\n".join(rows)


def render(reports: dict[str, dict[str, object]]) -> str:
    """Render the comparison markdown for a mapping of model -> metrics payload."""
    return (
        "# Model comparison\n\n"
        "_Generated by `python -m hinglish_mlops.compare` from the metrics reports._\n\n"
        "Selection is on the **validation** split; `test` and `shae_eval` are held out "
        "(`shae_eval` is out-of-distribution and never used for tuning).\n\n"
        "## Macro-F1\n\n"
        f"{_table('macro_f1', reports)}\n\n"
        "## Accuracy\n\n"
        f"{_table('accuracy', reports)}\n"
    )


def build(reports_dir: Path = REPORTS_DIR) -> Path:
    """Write ``reports/model_comparison.md`` from available metrics reports."""
    reports = {}
    for name in MODEL_BUILDERS:
        payload = load_metrics(name, reports_dir)
        if payload is not None:
            reports[name] = payload
    if not reports:
        raise FileNotFoundError(f"No metrics reports found in {reports_dir}; train a model first.")
    reports_dir.mkdir(parents=True, exist_ok=True)
    path = reports_dir / COMPARISON_FILE
    path.write_text(render(reports), encoding="utf-8", newline="\n")
    return path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Compare trained models.")
    parser.add_argument("--reports-dir", type=Path, default=REPORTS_DIR)
    args = parser.parse_args(argv)
    path = build(args.reports_dir)
    print(f"Wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
